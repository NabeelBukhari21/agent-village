    /// Maps typographic characters to ones the font has.
    static func normalize(_ s: String) -> String {
        var out = ""
        for ch in s {
            switch ch {
            case "“", "”": out.append("\"")
            case "‘", "’": out.append("'")
            case "—", "–": out.append("-")
            case "…": out += "..."
            case "✦", "✨": out.append("*")
            default:
                if ch == " " || glyphs[ch] != nil { out.append(ch) }
                else if let up = ch.uppercased().first, glyphs[up] != nil { out.append(up) }
            }
        }
        return out
    }

    static func width(of ch: Character) -> Int {
        ch == " " ? spaceWidth : (glyphs[ch]?.first?.count ?? 0)
    }

    static func measure(_ s: String) -> Int {
        let s = normalize(s)
        guard !s.isEmpty else { return 0 }
        return s.reduce(0) { $0 + width(of: $1) + 1 } - 1
    }

    static func draw(_ s: String, on c: PixelCanvas, x: Int, y: Int, color: PixelColor, shadow: PixelColor? = nil) {
        var cx = x
        for ch in normalize(s) {
            if ch != " ", let g = glyphs[ch] {
                for (j, row) in g.enumerated() {
                    for (i, p) in row.enumerated() where p == "#" {
                        if let shadow { c.set(cx + i, y + j + 1, shadow) }
                        c.set(cx + i, y + j, color)
                    }
                }
            }
            cx += width(of: ch) + 1
        }
    }

    /// Greedy word wrap to a pixel width.
    static func wrap(_ s: String, maxWidth: Int) -> [String] {
        var lines: [String] = [], line = ""
        for word in normalize(s).split(separator: " ", omittingEmptySubsequences: false) {
            let candidate = line.isEmpty ? String(word) : line + " " + word
            if measure(candidate) <= maxWidth || line.isEmpty { line = candidate }
            else { lines.append(line); line = String(word) }
        }
        if !line.isEmpty { lines.append(line) }
        return lines
    }

    /// Renders text to its own canvas, optionally with a 1px outline.
    static func render(_ s: String, color: PixelColor, outline: PixelColor? = nil, shadow: PixelColor? = nil) -> PixelCanvas {
        let pad = outline == nil ? 0 : 1
        let c = PixelCanvas(max(1, measure(s)) + pad * 2, lineHeight + pad * 2)
        draw(s, on: c, x: pad, y: pad, color: color, shadow: shadow)
        if let outline { c.outline(outline, diagonal: true) }
        return c
    }
